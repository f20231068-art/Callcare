"""Console mode: test Gnani's agent WITHOUT a Platform API key.

You do three things in the Gnani Agent Builder console (one-off per use case); everything else is automatic:
  1. paste the exported system prompt / greeting / closing message into your agent (`carecall gnani-export`)
  2. add the Twilio persona number under Phone Numbers -> Whitelisted, and set the agent's post-call webhook to
     <PUBLIC_BASE_URL>/gnani/webhook  (header  Authorization: Bearer <GNANI_WEBHOOK_TOKEN>)
  3. for each persona, click  Test -> Trigger Agent Call -> (persona number) -> Start Testing   when this tool says so

Our server answers each call as the next armed persona (an LLM plays the parent). When the call ends, Gnani POSTs the
transcript to our webhook, and we judge it exactly like every other run (rubric + checks + Langfuse + notes)."""
import time
from datetime import datetime
from pathlib import Path

from .. import tracing
from ..config import get_settings
from ..gnani_platform import agent_context, opening_for, system_prompt_for
from ..llm.factory import make_judge_client, make_llm_client
from ..net import http_client
from ..prompts import USECASES
from .gnani_runner import asr_fidelity, judge_call, preflight
from .persona_runner import build_report
from .personas import load_personas
from .runner import finalize_run

ALIAS = "Asha"  # the name baked into the console agent's prompt; every persona answers to it on the call

README = """# Gnani console setup (generated by `carecall gnani-export`)

For each use case folder below, open your agent in the Gnani Agent Builder console and:

1. **System prompt** <- paste `system_prompt.txt`
2. **Greeting message** <- paste `greeting.txt`;  **End message** <- paste `end_message.txt`
3. **Model**: Pampa Go (or Pampa Priority), temperature 0.3, max tokens 200; **language** en-IN; barge-in on
4. **Post-call webhook**: URL `{base}/gnani/webhook`, method POST, header `Authorization: Bearer {token}`
5. **Phone Numbers -> Whitelisted -> Add Number**: your Twilio persona number ({number}); an OTP is sent to it
   (`carecall twilio-otp` shows an SMS OTP if the number can receive SMS)

The prompt is rendered for a parent called "{alias}" and caregiver "Sree"; every persona answers to that name.
Run one use case at a time: set up its prompt, then `carecall gnani-personas --console --usecase <name>`.
"""


def export_setup(out: str = "gnani_agent_setup") -> Path:
    s = get_settings()
    root = Path(out)
    for uc in USECASES:
        card = {**next(p for p in load_personas() if p["usecase"] == uc), "name": f"{ALIAS}, 70"}
        ctx = agent_context(card)
        greeting, end = opening_for(uc, ctx, s.medicine_lead_minutes)
        d = root / uc
        d.mkdir(parents=True, exist_ok=True)
        (d / "system_prompt.txt").write_text(system_prompt_for(uc, ctx), encoding="utf-8")
        (d / "greeting.txt").write_text(greeting, encoding="utf-8")
        (d / "end_message.txt").write_text(end, encoding="utf-8")
    (root / "README.md").write_text(README.format(
        base=s.public_base_url.rstrip("/") or "<PUBLIC_BASE_URL>", token=s.gnani_webhook_token or "<GNANI_WEBHOOK_TOKEN>",
        number=s.persona_phone_e164 or "<PERSONA_PHONE_E164>", alias=ALIAS), encoding="utf-8")
    return root


def run_console(usecase: str, ids: list[str] | None = None, out_root: str = "runs", call_wait: float = 900,
                webhook_wait: float = 180) -> dict:
    s = get_settings()
    problems = [p for p in preflight(need_calls=True) if "GNANI_PLATFORM_API_KEY" not in p]  # the API key is NOT needed here
    if not s.gnani_webhook_token:
        problems.append("GNANI_WEBHOOK_TOKEN is empty: choose any long random string; the console webhook must send it.")
    if problems:
        raise SystemExit("Cannot start console-mode calls yet:\n" + "\n".join(f" - {p}" for p in problems))
    cards = [c for c in load_personas([usecase], ids)]
    client = make_judge_client()
    run_id = "gc-" + datetime.now().strftime("%Y%m%d-%H%M%S")
    out = Path(out_root) / run_id
    server = s.persona_server_url.rstrip("/")
    http = http_client(15)
    records, errors = [], []
    print(f"\nUse case: {usecase}. Make sure the console agent has the matching prompt (carecall gnani-export).")
    for n, card in enumerate(cards, 1):
        print(f"\n== [{n}/{len(cards)}] {card['id']}: {card['profile'][:90]}")
        armed = time.time()
        job_id = http.post(f"{server}/persona/jobs", json={"persona_id": card["id"], "alias": ALIAS}).json()["job_id"]
        print(f"   ARMED. Now in the Gnani console: Test -> Trigger Agent Call -> {s.persona_phone_e164} -> Start Testing", flush=True)
        end = time.time() + call_wait
        job = {}
        while time.time() < end:
            job = http.get(f"{server}/persona/jobs/{job_id}").json()
            if job["state"] in ("done", "error"):
                break
            time.sleep(3)
        else:
            errors.append({"id": card["id"], "error": "no call arrived within the wait window"})
            print("   ERROR: no call arrived")
            continue
        print("   call finished, waiting for Gnani's post-call webhook ...", flush=True)
        payload, stop = None, time.time() + webhook_wait
        while time.time() < stop and payload is None:
            payload = http.get(f"{server}/gnani/webhooks/next", params={"after": armed}).json().get("payload")
            if payload is None:
                time.sleep(3)
        if payload is None:
            errors.append({"id": card["id"], "error": "Gnani never POSTed the post-call webhook (URL/token set in the console?)"})
            print("   ERROR: no webhook")
            continue
        from ..gnani_platform import GnaniPlatform

        transcript = GnaniPlatform.transcript_of(payload)
        if not transcript:
            errors.append({"id": card["id"], "error": "webhook payload had no transcript"})
            continue
        heard = [t["text"] for t in transcript if t["speaker"] == "parent"]
        said = [t["text"] for t in job["transcript"] if t["speaker"] == "parent"]
        fid = asr_fidelity(said, heard)
        trace_id = tracing.new_trace_id()
        with tracing.call_span(trace_id, "gnani_call", 0, 0, card["routine"],
                               tags=["suite:gnani-personas", "mode:console", f"usecase:{usecase}", f"run:{run_id}", f"persona:{card['id']}"],
                               input={"persona": card["name"], "profile": card["profile"], "truth": card["truth"]},
                               trace_name=f"gnani:{card['id']}", session_id=f"{run_id}:{card['id']}",
                               metadata={"conversation": payload.get("conversation_id", ""), "asr_fidelity": fid}) as span:
            if span:
                span.update(output={"transcript": transcript, "disposition": payload.get("STAGE_CODE")})
        rec = judge_call({**card, "name": card["name"]}, transcript, client, trace_id, run_id, {
            "end_reason": str(payload.get("STAGE_CODE") or payload.get("callStatus") or ""), "asr_fidelity": fid,
            "persona_side_transcript": job["transcript"], "persona_tts_log": job.get("tts_log", []),
            "gnani_conversation_id": payload.get("conversation_id"), "call_infra": payload.get("call_infra", {})})
        tracing.score(trace_id, "eval_passed", 1.0 if rec["passed"] else 0.0, comment=card["id"], data_type="BOOLEAN")
        tracing.score(trace_id, "rubric_pass_rate", round(sum(c["passed"] for c in rec["checks"]) / len(rec["checks"]), 2), data_type="NUMERIC")
        tracing.score(trace_id, "gnani_asr_fidelity", fid, data_type="NUMERIC")
        records.append(rec)
        print(f"   {'PASS' if rec['passed'] else 'FAIL'}  (Gnani ASR fidelity {fid})", flush=True)

    if not records:
        raise SystemExit("every persona errored:\n" + "\n".join(f"  {e['id']}: {e['error']}" for e in errors))

    class _N:
        def __init__(self, name):
            self.name = name

    fids = [r["asr_fidelity"] for r in records]
    extra = [f"- mode: console + webhook (no Platform API key)  |  use case: {usecase}",
             f"- Gnani ASR fidelity on the persona's speech: mean {sum(fids) / len(fids):.2f}", ""]
    report = build_report(records, run_id, "llm-on-real-phone-call", "gnani-agent (console)", "llm-judge")
    if errors:
        report += ["## Personas that errored (not scored)"] + [f"- {e['id']}: {e['error']}" for e in errors] + [""]
    result = finalize_run(records, out, run_id, "Gnani persona run (console)", _N("gnani-agent (console)"), _N("llm-judge"),
                          extra_summary=extra)
    (out / "persona_report.md").write_text("\n".join(report), encoding="utf-8")
    result["report"], result["errors"] = str(out / "persona_report.md"), [e["id"] for e in errors]
    return result
